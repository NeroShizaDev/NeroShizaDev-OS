/// Вывод полной приборной панели племени.
/// Показывает всё: параметры, флаги, активные взаимодействия.
pub fn отобразить_всё(tribe: &Tribe) {
    clear_screen();

    // ── ЗАГОЛОВОК ──────────────────────────────────────────────
    print_separator(ЦВЕТ_РАМКА);
    print("  ", ЦВЕТ_ОБЫЧНЫЙ);
    print(tribe.name_str(), ЦВЕТ_ЗАГОЛОВОК);
    print("   Ход: ", ЦВЕТ_ОБЫЧНЫЙ);
    print_num(tribe.turn, ЦВЕТ_КРИТ);
    print("   Приказов: ", ЦВЕТ_ОБЫЧНЫЙ);
    print_num(tribe.ap_left as u32, ЦВЕТ_КРИТ);
    print("/", ЦВЕТ_ОБЫЧНЫЙ);
    print_num(tribe.ap_max as u32, ЦВЕТ_ОБЫЧНЫЙ);
    println("", ЦВЕТ_ОБЫЧНЫЙ);
    print_separator(ЦВЕТ_РАМКА);

    // ── ОСНОВНЫЕ ПАРАМЕТРЫ ─────────────────────────────────────
    println("  [ ПАРАМЕТРЫ ]", ЦВЕТ_ЗАГОЛОВОК);
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    // Еда с цветом и предупреждением
    print("  Еда:        ", ЦВЕТ_ОБЫЧНЫЙ);
    let еда_цвет = if tribe.food < 0 { ЦВЕТ_ПРОВАЛ }
                   else if tribe.food < 5 { ЦВЕТ_КРИТ }
                   else { ЦВЕТ_УСПЕХ };
    print_inum(tribe.food, еда_цвет);
    if tribe.food < 0 { print("  ← ГОЛОД", ЦВЕТ_ПРОВАЛ); }
    else if tribe.food < 5 { print("  ← мало", ЦВЕТ_КРИТ); }
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    // Население
    print("  Население:  ", ЦВЕТ_ОБЫЧНЫЙ);
    let нас_цвет = if tribe.population < 5 { ЦВЕТ_ПРОВАЛ }
                   else if tribe.population < 8 { ЦВЕТ_КРИТ }
                   else { ЦВЕТ_ОБЫЧНЫЙ };
    print_num(tribe.population, нас_цвет);
    if tribe.population < 5 { print("  ← критично", ЦВЕТ_ПРОВАЛ); }
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    // Знания с уровнями
    print("  Знания:     ", ЦВЕТ_ОБЫЧНЫЙ);
    print_num(tribe.knowledge, ЦВЕТ_ОБЫЧНЫЙ);
    let зн_уровень = match tribe.knowledge {
        0..=19   => "  [наивные]",
        20..=49  => "  [обычные]",
        50..=99  => "  [опытные]",
        100..=199 => "  [мудрые]",
        _        => "  [УЧЁНЫЕ]",
    };
    println(зн_уровень, ЦВЕТ_ПОДСКАЗКА);

    // Настроение с индикатором
    print("  Настроение: ", ЦВЕТ_ОБЫЧНЫЙ);
    let н_цвет = if tribe.mood < -5 { ЦВЕТ_ПРОВАЛ }
                 else if tribe.mood < 0 { ЦВЕТ_КРИТ }
                 else if tribe.mood > 5 { ЦВЕТ_УСПЕХ }
                 else { ЦВЕТ_ОБЫЧНЫЙ };
    print_inum(tribe.mood as i32, н_цвет);
    // Графический индикатор -10..+10
    print("  [", ЦВЕТ_ОБЫЧНЫЙ);
    for i in -10i8..=10 {
        let ch = if i <= tribe.mood { '█' } else { '░' };
        let c = if tribe.mood < -5 { ЦВЕТ_ПРОВАЛ }
                else if tribe.mood > 5 { ЦВЕТ_УСПЕХ }
                else { ЦВЕТ_КРИТ };
        if i == 0 { print("|", ЦВЕТ_ПОДСКАЗКА); }
        else {
            let s: [u8; 4] = [ch as u8, 0, 0, 0];
            // вывод одного символа
            for b in s {
                if b != 0 { print_char_adv(ch, c); break; }
            }
        }
    }
    println("]", ЦВЕТ_ОБЫЧНЫЙ);

    // Авторитет с индикатором
    print("  Авторитет:  ", ЦВЕТ_ОБЫЧНЫЙ);
    let а_цвет = if tribe.authority < -3 { ЦВЕТ_ПРОВАЛ }
                 else if tribe.authority > 5 { ЦВЕТ_УСПЕХ }
                 else { ЦВЕТ_ОБЫЧНЫЙ };
    print_inum(tribe.authority as i32, а_цвет);
    if tribe.authority < -5 { print("  ← племя не доверяет", ЦВЕТ_ПРОВАЛ); }
    else if tribe.authority > 7 { print("  ← ЛЕГЕНДАРНЫЙ ВОЖДЬ", ЦВЕТ_УСПЕХ); }
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    println("", ЦВЕТ_ОБЫЧНЫЙ);
    print_separator(ЦВЕТ_РАМКА);

    // ── АТРИБУТЫ GURPS ─────────────────────────────────────────
    println("  [ GURPS АТРИБУТЫ ПЛЕМЕНИ ]", ЦВЕТ_ЗАГОЛОВОК);
    println("", ЦВЕТ_ОБЫЧНЫЙ);
    print("  СИЛ: ", ЦВЕТ_ОБЫЧНЫЙ); print_num(tribe.str_ as u32, ЦВЕТ_КРИТ);
    print("  ЛОВ: ", ЦВЕТ_ОБЫЧНЫЙ); print_num(tribe.dex as u32, ЦВЕТ_КРИТ);
    print("  ИНТ: ", ЦВЕТ_ОБЫЧНЫЙ); print_num(tribe.int_ as u32, ЦВЕТ_КРИТ);
    print("  ЗДР: ", ЦВЕТ_ОБЫЧНЫЙ); print_num(tribe.hlt as u32, ЦВЕТ_КРИТ);
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    // Расчёт эффективной цели для каждого действия
    println("", ЦВЕТ_ОБЫЧНЫЙ);
    println("  Цели бросков (3d6 ≤ цели = успех):", ЦВЕТ_ПОДСКАЗКА);
    let названия = ["  Охота:    ", "  Сбор:     ", "  Думать:   ", "  Разведка: "];
    for i in 0u8..4 {
        print(названия[i as usize], ЦВЕТ_ОБЫЧНЫЙ);
        let цель = effective_target(tribe, i, false);
        let цвет = if цель >= 13 { ЦВЕТ_УСПЕХ }
                   else if цель >= 10 { ЦВЕТ_КРИТ }
                   else { ЦВЕТ_ПРОВАЛ };
        print_num(цель as u32, цвет);
        print(" / тупой: ", ЦВЕТ_ПОДСКАЗКА);
        print_num(effective_target(tribe, i, true) as u32, ЦВЕТ_ПОДСКАЗКА);
        println("", ЦВЕТ_ОБЫЧНЫЙ);
    }

    println("", ЦВЕТ_ОБЫЧНЫЙ);
    print_separator(ЦВЕТ_РАМКА);

    // ── АКТИВНЫЕ ФЛАГИ ─────────────────────────────────────────
    println("  [ ФЛАГИ МИРА ]", ЦВЕТ_ЗАГОЛОВОК);
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    let mut есть_флаги = false;
    for (флаг, название, описание) in ТАБЛИЦА_ФЛАГОВ.iter() {
        if tribe.has_flag(*флаг) {
            есть_флаги = true;
            let цвет = if описание.starts_with('!') { ЦВЕТ_ПРОВАЛ }
                       else if описание.starts_with('+') { ЦВЕТ_УСПЕХ }
                       else { ЦВЕТ_КРИТ };
            print("  ■ ", цвет);
            print(название, ЦВЕТ_ОБЫЧНЫЙ);
            print(": ", ЦВЕТ_ПОДСКАЗКА);
            println(описание, цвет);
        }
    }
    if !есть_флаги {
        println("  (нет активных флагов)", ЦВЕТ_ПОДСКАЗКА);
    }

    println("", ЦВЕТ_ОБЫЧНЫЙ);
    print_separator(ЦВЕТ_РАМКА);

    // ── АКТИВНЫЕ ВЗАИМОДЕЙСТВИЯ ─────────────────────────────────
    println("  [ АКТИВНЫЕ СВЯЗКИ ]", ЦВЕТ_ЗАГОЛОВОК);
    println("", ЦВЕТ_ОБЫЧНЫЙ);

    let mut есть_связки = false;

    // Показываем какие связки сейчас активны
    for (условие, текст, цвет) in ТАБЛИЦА_СВЯЗОК.iter() {
        if условие(tribe) {
            есть_связки = true;
            print("  → ", *цвет);
            println(текст, ЦВЕТ_ОБЫЧНЫЙ);
        }
    }

    if !есть_связки {
        println("  (нет активных взаимодействий)", ЦВЕТ_ПОДСКАЗКА);
    }

    println("", ЦВЕТ_ОБЫЧНЫЙ);
    print_separator(ЦВЕТ_РАМКА);

    // ── ИСТОРИЯ (последние 4 хода) ──────────────────────────────
    println("  [ ПОСЛЕДНИЕ СОБЫТИЯ ]", ЦВЕТ_ЗАГОЛОВОК);
    println("", ЦВЕТ_ОБЫЧНЫЙ);
    tribe.log.display_last(4);

    print_separator(ЦВЕТ_РАМКА);
    println("  [1-5] Выбрать действие  [H] История  [Esc] Меню", ЦВЕТ_ПОДСКАЗКА);
}

