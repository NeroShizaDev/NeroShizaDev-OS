/// Бинарный поиск скрипта по кодпоинту — O(log n)
pub fn find_script(cp: u32) -> Script {
    let mut lo = 0usize;
    let mut hi = 2287;
    while lo < hi {
        let mid = lo + (hi - lo) / 2;
        let (start, end, script) = SCRIPT_RANGES[mid];
        if cp < start {
            hi = mid;
        } else if cp > end {
            lo = mid + 1;
        } else {
            return script;
        }
    }
    Script::Common // По умолчанию
}

