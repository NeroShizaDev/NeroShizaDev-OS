// Кириллический шрифт 8x16 для VGA text mode
// Каждая буква = 16 байт (16 строк по 8 пикселей)
// Буквы нарисованы "из палочек" — пиксельная графика

/// Загружает кириллический шрифт в VGA plane 2
/// Символы размещаются в позициях 128..192 (64 символа)
/// Порядок: А Б В Г Д Е Ж З И Й К Л М Н О П Р С Т У Ф Х Ц Ч Ш Щ Ъ Ы Ь Э Ю Я
///          а б в г д е ж з и й к л м н о п р с т у ф х ц ч ш щ ъ ы ь э ю я
pub unsafe fn load_cyrillic_font() {
    unsafe {
    use x86_64::instructions::port::Port;

    let mut seq_index: Port<u8> = Port::new(0x3C4);
    let mut seq_data: Port<u8> = Port::new(0x3C5);
    let mut gc_index: Port<u8> = Port::new(0x3CE);
    let mut gc_data: Port<u8> = Port::new(0x3CF);

    // === Переключаемся в режим записи шрифта ===
    // Sequencer: пишем в plane 2, sequential mode
    seq_index.write(0x02);
    seq_data.write(0x04);   // Map Mask: plane 2 only
    seq_index.write(0x04);
    seq_data.write(0x06);   // Memory Mode: sequential, no odd/even

    // Graphics Controller: читаем plane 2, линейный доступ, маппим на A0000
    gc_index.write(0x04);
    gc_data.write(0x02);    // Read Map Select: plane 2
    gc_index.write(0x05);
    gc_data.write(0x00);    // Graphics Mode: write mode 0, read mode 0
    gc_index.write(0x06);
    gc_data.write(0x00);    // Misc Graphics: A0000-BFFFF, no chain odd/even

    // Указатель на шрифт: plane 2 маппится на 0xA0000
    // Каждый символ = 32 байт (используем первые 16)
    let font_base = 0xA0000 as *mut u8;

    // Записываем глифы для символов 128..192
    for (i, glyph) in CYRILLIC_GLYPHS.iter().enumerate() {
        let char_offset = (128 + i) * 32;
        for (row, &byte) in glyph.iter().enumerate() {
            core::ptr::write_volatile(font_base.add(char_offset + row), byte);
        }
        // Обнуляем оставшиеся 16 байт
        for row in 16..32 {
            core::ptr::write_volatile(font_base.add(char_offset + row), 0);
        }
    }

    // === Восстанавливаем нормальный текстовый режим VGA ===
    // Sequencer: пишем в planes 0+1, odd/even mode
    seq_index.write(0x02);
    seq_data.write(0x03);   // Map Mask: planes 0 и 1
    seq_index.write(0x04);
    seq_data.write(0x02);   // Memory Mode: odd/even

    // Graphics Controller: возврат в текстовый режим
    gc_index.write(0x04);
    gc_data.write(0x00);    // Read Map Select: plane 0
    gc_index.write(0x05);
    gc_data.write(0x10);    // Graphics Mode: odd/even
    gc_index.write(0x06);
    gc_data.write(0x0E);    // Misc: B8000-BFFFF, text mode
    } // unsafe
}

/// Преобразует UTF-8 кириллический символ в наш VGA-код (128+)
/// Возвращает None если символ не кириллический
pub fn cyrillic_to_vga(c: char) -> Option<u8> {
    match c {
        // Заглавные: А=128, Б=129, ... Я=159
        'А' => Some(128), 'Б' => Some(129), 'В' => Some(130), 'Г' => Some(131),
        'Д' => Some(132), 'Е' => Some(133), 'Ж' => Some(134), 'З' => Some(135),
        'И' => Some(136), 'Й' => Some(137), 'К' => Some(138), 'Л' => Some(139),
        'М' => Some(140), 'Н' => Some(141), 'О' => Some(142), 'П' => Some(143),
        'Р' => Some(144), 'С' => Some(145), 'Т' => Some(146), 'У' => Some(147),
        'Ф' => Some(148), 'Х' => Some(149), 'Ц' => Some(150), 'Ч' => Some(151),
        'Ш' => Some(152), 'Щ' => Some(153), 'Ъ' => Some(154), 'Ы' => Some(155),
        'Ь' => Some(156), 'Э' => Some(157), 'Ю' => Some(158), 'Я' => Some(159),
        // Строчные: а=160, б=161, ... я=191
        'а' => Some(160), 'б' => Some(161), 'в' => Some(162), 'г' => Some(163),
        'д' => Some(164), 'е' => Some(165), 'ж' => Some(166), 'з' => Some(167),
        'и' => Some(168), 'й' => Some(169), 'к' => Some(170), 'л' => Some(171),
        'м' => Some(172), 'н' => Some(173), 'о' => Some(174), 'п' => Some(175),
        'р' => Some(176), 'с' => Some(177), 'т' => Some(178), 'у' => Some(179),
        'ф' => Some(180), 'х' => Some(181), 'ц' => Some(182), 'ч' => Some(183),
        'ш' => Some(184), 'щ' => Some(185), 'ъ' => Some(186), 'ы' => Some(187),
        'ь' => Some(188), 'э' => Some(189), 'ю' => Some(190), 'я' => Some(191),
        // Ё/ё — маппим на Е/е
        'Ё' => Some(133), 'ё' => Some(165),
        _ => None,
    }
}

