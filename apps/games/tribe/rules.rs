// ЧАСТЬ 2: КОНТЕКСТ РЕЗУЛЬТАТА — текст зависит от состояния
// После броска выбираем какой именно текст показать.
// Это и есть "нарративное полотно".
// ═══════════════════════════════════════════════════════════════════

/// Контекст для выбора текста события.
/// Возвращает &str — переопределяющий текст или None (использовать базовый).
pub fn contextual_override<'a>(
    tribe: &Tribe,
    действие: u8,
    исход: Outcome,
) -> Option<&'a str> {

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: Голод + Успех = горький успех
    // "Поели. Но в глазах вопрос: надолго ли?"
    if tribe.food < 5 && исход == Outcome::Success {
        match действие {
            0 => return Some("Добыча есть. Но все знают — это ненадолго. Тревога не уходит."),
            1 => return Some("Принесли. Поели. Завтра снова придётся искать. Уныние."),
            _ => {}
        }
    }

    // СВЯЗКА: Голод + Крит Успех = облегчение со слезами
    if tribe.food < 0 && исход == Outcome::CritSuccess {
        return Some("НАКОНЕЦ. Все едят молча. Некоторые плачут. Давно так хорошо не было.");
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: Знания > 100 + Крит Провал ДУМАТЬ = мудрость спасает
    // "Знания выступают буфером от катастрофы"
    if tribe.knowledge > 100 && действие == 2 && исход == Outcome::CritFail {
        return Some("Дед Ых вспомнил старую историю про мамонта. Все засмеялись. Драка не случилась. +10 знаний.");
    }

    // СВЯЗКА: Знания > 150 + Крит Провал = вообще не крит
    if tribe.knowledge > 150 && исход == Outcome::CritFail {
        return Some("Мудрость племени не позволила катастрофе случиться. Просто провал. Не конец.");
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: Авторитет < -5 + Успех = успех без признания
    // "Ты всё сделал правильно. Тебя всё равно осуждают."
    if tribe.authority < -5 && (исход == Outcome::Success || исход == Outcome::CritSuccess) {
        return Some("Добыча принесена. Племя ест. Но вождя не благодарят. Авторитет упал ещё ниже.");
    }

    // СВЯЗКА: Авторитет > 7 + Крит Успех = легендарный момент
    if tribe.authority > 7 && исход == Outcome::CritSuccess {
        return Some("ЭТО ВОЙДЁТ В ЛЕГЕНДЫ. Шаман уже складывает слова. Племя будет помнить.");
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: НАС_ИЗУЧАЮТ + Голод + Провал = наблюдатели видят слабость
    if tribe.has_flag(flags::НАС_ИЗУЧАЮТ) && tribe.food < 5
        && исход == Outcome::Fail {
        return Some("Провал. Чужаки за холмом наблюдают. Они видели. Они всё видели.");
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: ПРОКЛЯТЫЕ_ЛИСТЬЯ + любой сбор = листья вмешиваются
    if tribe.has_flag(flags::ПРОКЛЯТЫЕ_ЛИСТЬЯ) && действие == 1 {
        match исход {
            Outcome::Fail | Outcome::CritFail => {
                return Some("Листья у входа пещеры смотрели на провал. Шаман говорит: виноваты листья.");
            }
            _ => {}
        }
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: КУЛЬТ_БЕССМЕРТНОГО + охота = запрет
    if tribe.has_flag(flags::КУЛЬТ_БЕССМЕРТНОГО) && действие == 0 {
        if исход == Outcome::CritFail {
            return Some("ЗВЕРЬ СНОВА УШЁЛ. НЕУБИВАЕМЫЙ. Половина племени требует прекратить охоту на него.");
        }
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: ДЕЗЕРТИР + любое действие = нехватка рук
    if tribe.has_flag(flags::ДЕЗЕРТИР) && (исход == Outcome::Fail || исход == Outcome::CritFail) {
        return Some("Не хватает людей. Тот кто ушёл — умел делать это лучше всех. Пустота.");
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: Уныние (mood <= -8) + любой провал = отчаяние
    if tribe.mood <= -8 && (исход == Outcome::Fail || исход == Outcome::CritFail) {
        return Some("Никто не удивился. Все ожидали худшего. Племя перестаёт верить.");
    }

    // СВЯЗКА: Воодушевление (mood >= 8) + любой успех = эйфория
    if tribe.mood >= 8 && (исход == Outcome::Success || исход == Outcome::CritSuccess) {
        return Some("ВОЖДЬ ВЕДЁТ! Племя работает с огнём в глазах. Всё получается.");
    }

    // ────────────────────────────────────────────────────────────
    // СВЯЗКА: ПЕРВОЕ_ПИСЬМО + ДУМАТЬ крит успех = прорыв
    if tribe.has_flag(flags::ПЕРВОЕ_ПИСЬМО) && действие == 2
        && исход == Outcome::CritSuccess {
        return Some("Шаман записал мысль. Впервые мысль не умрёт вместе с думавшим. Это меняет всё.");
    }

    // СВЯЗКА: ФИЛОСОФИЯ + ДУМАТЬ провал = продуктивный провал
    if tribe.has_flag(flags::ФИЛОСОФИЯ) && действие == 2
        && исход == Outcome::Fail {
        return Some("Не пришли к ответу. Но вопрос стал точнее. Может это и есть прогресс.");
    }

    None // Используем базовый текст
}

