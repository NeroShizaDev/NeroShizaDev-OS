pub fn получить_обычное(
    действие: usize,
    исход: usize,
    индекс: usize,
) -> &'static EventCard {
    match действие {
        0 => &ОХОТА_ОБ[исход][индекс],
        1 => &СБОР_ОБ[исход][индекс],
        2 => &ДУМАТЬ_ОБ[исход][индекс],
        3 => &РАЗВЕДКА_ОБ[исход][индекс],
        _ => &ОХОТА_ОБ[2][0],
    }
}

pub fn получить_тупое(
    действие: usize,
    вариант: usize,
    исход: usize,
    индекс: usize,
) -> &'static EventCard {
    match действие {
        0 => &ОХОТА_ТУП[вариант][исход][индекс],
        1 => &СБОР_ТУП[вариант][исход][индекс],
        2 => &ДУМАТЬ_ТУП[вариант][исход][индекс],
        3 => &РАЗВЕДКА_ТУП[вариант][исход][индекс],
        4 => &НИЧЕГО_ТУП[исход][индекс],
        _ => &ОХОТА_ТУП[0][2][0],
    }
}

pub fn получить_системное(
    категория: usize, суб: usize
) -> &'static EventCard {
    &СИСТЕМНЫЕ[категория.min(2)][суб.min(5)]
}

pub fn статистика() -> (usize, usize, usize) {
    (4 * 4 * 6, 5 * 3 * 4 * 6, 3 * 6) // 96 + 360 + 18 = 474
}
