//
// Здесь живёт настоящая магия.
// Рандомайзер — это барабан.
// Таблица взаимодействий — это то, за что молятся в Dwarf Fortress.
//
// Каждый параметр знает о других параметрах.
// Каждый флаг меняет смысл броска.
// Голод делает успех горьким. Знания смягчают провал.
// Авторитет — это валюта. Настроение — это давление.
//
// АРХИТЕКТУРА:
//   1. Модификатор броска (до броска) — параметры меняют цель
//   2. Контекст результата (после броска) — параметры меняют ТЕКСТ
//   3. Каскадные эффекты (после результата) — флаги запускают цепочки
//   4. Фаза DM (каждый ход) — мир живёт без команды игрока
//
// ═══════════════════════════════════════════════════════════════════

use crate::tribe::{Tribe, flags};
use crate::db::{Eff, EventCard};
use crate::gurps::Outcome;

// ═══════════════════════════════════════════════════════════════════
// ЧАСТЬ 1: МОДИФИКАТОР БРОСКА
// Параметры меняют цель GURPS ДО броска.
// Базовая цель = 11 (средний человек).
// ═══════════════════════════════════════════════════════════════════

/// Рассчитывает эффективную цель броска с учётом всех параметров.
/// Больше = легче (GURPS: успех если бросок ≤ цели).
pub fn effective_target(tribe: &Tribe, действие: u8, тупой: bool) -> u8 {
    let mut target: i16 = 11; // Базовая цель GURPS

    // ── ЗНАНИЯ: опыт помогает всему ────────────────────────────
    // 0-19 зн: -2 (наивные)
    // 20-49 зн: +0 (норма)
    // 50-99 зн: +1 (опытные)
    // 100-199 зн: +2 (мудрые)
    // 200+ зн: +3 (учёные)
    let знания_бонус: i16 = match tribe.knowledge {
        0..=19   => -2,
        20..=49  =>  0,
        50..=99  =>  1,
        100..=199 => 2,
        _        =>  3,
    };
    target += знания_бонус;

    // ── НАСТРОЕНИЕ: счастливые работают лучше ──────────────────
    // настроение -10..-6: -2 (уныние)
    // настроение -5..-2: -1 (плохо)
    // настроение -1..+2: +0 (норма)
    // настроение +3..+6: +1 (хорошо)
    // настроение +7..+10: +2 (воодушевление)
    let настроение_мод: i16 = match tribe.mood {
        i if i <= -6 => -2,
        i if i <= -2 => -1,
        i if i <= 2  =>  0,
        i if i <= 6  =>  1,
        _            =>  2,
    };
    target += настроение_мод;

    // ── ГОЛОД: голодные делают ошибки ──────────────────────────
    // food > 20: +1 (сыты)
    // food 10-20: +0 (норма)
    // food 1-9: -1 (впроголодь)
    // food 0: -2 (голод)
    // food < 0: -3 (страдание)
    let голод_штраф: i16 = match tribe.food {
        i if i > 20 =>  1,
        i if i > 9  =>  0,
        i if i > 0  => -1,
        0           => -2,
        _           => -3,
    };
    target += голод_штраф;

    // ── АВТОРИТЕТ: вождь задаёт тон ────────────────────────────
    // авторитет > 5: +1 (племя верит вождю и старается)
    // авторитет < -3: -1 (саботаж)
    let авт_мод: i16 = if tribe.authority > 5 { 1 }
                       else if tribe.authority < -3 { -1 }
                       else { 0 };
    target += авт_мод;

    // ── НАСЕЛЕНИЕ: маленькое племя перегружено ─────────────────
    // население < 5: -2 (все делают всё)
    // население 5-8: -1 (тяжело)
    // население 9-14: +0 (норма)
    // население 15-20: +1 (есть специализация)
    // население > 20: +2 (организация)
    let нас_мод: i16 = match tribe.population {
        0..=4  => -2,
        5..=8  => -1,
        9..=14 =>  0,
        15..=20 => 1,
        _      =>  2,
    };
    target += нас_мод;

    // ── МОДИФИКАТОРЫ ФЛАГОВ ─────────────────────────────────────

    // Ловушки: охота легче
    if tribe.has_flag(flags::ЛОВУШКИ) && действие == 0 {
        target += 1;
    }

    // Тропа зверей известна: охота + разведка легче
    if tribe.has_flag(flags::ТРОПА_ЗВЕРЕЙ) && (действие == 0 || действие == 3) {
        target += 1;
    }

    // Корзины: сбор эффективнее
    if tribe.has_flag(flags::КОРЗИНЫ) && действие == 1 {
        target += 1;
    }

    // Традиция загадок: думать легче
    if tribe.has_flag(flags::ТРАДИЦИЯ_ЗАГАДОК) && действие == 2 {
        target += 1;
    }

    // Враги знают где мы: разведка опаснее
    if tribe.has_flag(flags::ВРАГИ_ЗНАЮТ) && действие == 3 {
        target -= 2;
    }

    // Медведь помнит: каждые 5 ходов штраф к охоте
    if tribe.has_flag(flags::МЕДВЕДЬ_ПОМНИТ) && действие == 0
        && tribe.turn % 5 == 0 {
        target -= 3;
    }

    // Первый волк: разведка легче
    if tribe.has_flag(flags::ПЕРВЫЙ_ВОЛК) && действие == 3 {
        target += 1;
    }

    // Репутация духов: все броски +1 (враги боятся)
    if tribe.has_flag(flags::РЕПУТАЦИЯ_ДУХОВ) {
        target += 1;
    }

    // По-тупому: базовая цель ниже (тупость добавляет риск)
    if тупой {
        target -= 1; // сложнее... но и выигрыш больше
    }

    // Уныние: если mood <= -7, штраф ОД уже снижает население
    // но и бросок страдает
    if tribe.mood <= -7 {
        target -= 1;
    }

    // Ограничение: 4..=18 (всегда есть шанс на крит в обе стороны)
    target.clamp(4, 18) as u8
}

