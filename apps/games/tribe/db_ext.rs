// ─── Функции доступа к расширенным таблицам ──────────────────

/// Получить тупой вариант с расширенными индексами (0..5)
/// variant 0..2 → основная таблица (db.rs)
/// variant 3..5 → расширенная таблица (db_ext.rs)
pub fn получить_тупое_ext(
    действие: usize,
    вариант: usize,
    исход: usize,
    индекс: usize,
) -> &'static EventCard {
    if вариант < 3 {
        super::db::получить_тупое(действие, вариант, исход, индекс)
    } else {
        let v = вариант - 3;
        match действие {
            0 => &ОХОТА_ТУП2[v][исход][индекс],
            1 => &СБОР_ТУП2[v][исход][индекс],
            2 => &ДУМАТЬ_ТУП2[v][исход][индекс],
            3 => &РАЗВЕДКА_ТУП2[v][исход][индекс],
            _ => super::db::получить_тупое(0, 0, 2, 0),
        }
    }
}

/// Теперь тупых вариантов 6 (0..5): roll 1d6-1
pub fn вариантов_тупых() -> u8 {
    6
}
