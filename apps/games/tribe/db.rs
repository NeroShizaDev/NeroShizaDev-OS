#[derive(Clone, Copy)]
pub enum Eff {
    Еда(i32),
    Знания(u32),
    Народ(i32),
    Флаг(u128),
    Авторитет(i8),
    Настроение(i8),
    ОД(u8),
    Набег(u8),
    Гости(u8),
    Конфликт(u8),
    БросокЗДР,
    БросокЛОВ,
    ЕдаПроц(i8),
    ЗнанияПроц(i8),
    ШтрафОхоты(u8),
    Ничего,
}

pub type Эфф = [Eff; 4];

pub const fn пусто() -> Эфф {
    [Eff::Ничего; 4]
}
pub const fn э1(a: Eff) -> Эфф {
    [a, Eff::Ничего, Eff::Ничего, Eff::Ничего]
}
pub const fn э2(a: Eff, b: Eff) -> Эфф {
    [a, b, Eff::Ничего, Eff::Ничего]
}
pub const fn э3(a: Eff, b: Eff, c: Eff) -> Эфф {
    [a, b, c, Eff::Ничего]
}

