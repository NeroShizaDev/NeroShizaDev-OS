static mut NOISE_IDX: usize = 0;

/// Возвращает псевдослучайное число [0, max)
fn lcg_rand(max: u8) -> u8 {
    // SAFETY: NOISE_IDX — static mut usize; функция вызывается только из
    // главного game loop (однопоточное ядро, прерывания отключены) —
    // гонок данных нет. NOISE_TABLE индексируется по NOISE_IDX % 256,
    // результат всегда в пределах [0, 256).
    unsafe {
        let val = NOISE_TABLE[NOISE_IDX % 256];
        NOISE_IDX = (NOISE_IDX + 1) % 256;
        val % max.max(1)
    }
}

/// Добавляет RDRAND-шум к яркости (±8 уровней).
/// При недоступности RDRAND — LCG fallback.
///
/// # Параметры
/// * `brightness` — текущий уровень яркости пикселя (0..FIRE_LEVELS)
/// * Возвращает скорректированный уровень в пределах [0, FIRE_LEVELS)
pub fn chaos_lighting(brightness: u8, max_level: u8) -> u8 {
    let noise: i16 = if crate::rng::is_supported() {
        match crate::rng::random_u64() {
            Some(r) => ((r & 0x0F) as i16) - 8,  // [-8, +7]
            None    => lcg_rand(16) as i16 - 8,
        }
    } else {
        lcg_rand(16) as i16 - 8
    };

    let result = brightness as i16 + noise;
    result.clamp(0, (max_level - 1) as i16) as u8
}

/// Возвращает случайный bool с заданной вероятностью (prob / 256).
pub fn random_chance(prob: u8) -> bool {
    match crate::rng::random_u64() {
        Some(r) => (r as u8) < prob,
        None    => lcg_rand(255) < prob,
    }
}

/// Случайный u8 [0, max)
pub fn rand_u8(max: u8) -> u8 {
    match crate::rng::random_u64() {
        Some(r) => (r as u8) % max.max(1),
        None    => lcg_rand(max),
    }
}
