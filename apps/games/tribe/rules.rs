// ЧАСТЬ 3: КАСКАДНЫЕ ЭФФЕКТЫ — флаги запускают цепочки
// Применяются ПОВЕРХ базовых эффектов события.
// Это "невидимые модификаторы" которые игрок открывает со временем.
// ═══════════════════════════════════════════════════════════════════

/// Дополнительные эффекты от взаимодействия параметров.
/// Применяются после базовых эффектов события.
pub struct КаскадЭфф {
    pub еда:        i32,
    pub знания:     i32,
    pub народ:      i32,
    pub авторитет:  i8,
    pub настроение: i8,
    pub текст:      Option<&'static str>,
    pub флаг_снять: Option<u128>,
    pub флаг_ставить: Option<u128>,
}

impl КаскадЭфф {
    pub const fn пусто() -> Self {
        Self {
            еда: 0, знания: 0, народ: 0,
            авторитет: 0, настроение: 0,
            текст: None,
            флаг_снять: None,
            флаг_ставить: None,
        }
    }
}

/// Вычисляет каскадные эффекты ДО применения события.
/// Порядок: сначала базовый эффект из db.rs, потом каскад.
pub fn cascade(tribe: &Tribe, действие: u8, исход: Outcome) -> КаскадЭфф {
    let mut к = КаскадЭфф::пусто();

    // ────────────────────────────────────────────────────────────
    // ОГОНЬ: еда не портится зимой (убираем штраф ливня)
    // Реализовано как бонус к сбору в плохую погоду
    if tribe.has_flag(flags::ОГОНЬ) && действие == 1 && tribe.turn % 8 == 0 {
        к.еда += 3;
        к.текст = Some("Огонь сохраняет еду. Небольшой бонус к запасам.");
    }

    // ПЕРВОЕ_ПИСЬМО: +2 знания автоматически каждый ход
    if tribe.has_flag(flags::ПЕРВОЕ_ПИСЬМО) {
        к.знания += 2;
    }

    // ────────────────────────────────────────────────────────────
    // ГОЛОД ЗАПУСКАЕТ ДЕЗЕРТИРСТВО
    if tribe.food < 0 && tribe.mood < -5 {
        // Риск дезертирства при каждом крит провале
        if исход == Outcome::CritFail {
            к.народ -= 1;
            к.флаг_ставить = Some(flags::ДЕЗЕРТИР);
            к.текст = Some("Кто-то не выдержал. Ушёл ночью. Голод и уныние сломали его.");
        }
    }

    // ────────────────────────────────────────────────────────────
    // НАС_ИЗУЧАЮТ + голод + провал = соседи делают предложение
    if tribe.has_flag(flags::НАС_ИЗУЧАЮТ) && tribe.food < 3
        && (исход == Outcome::Fail || исход == Outcome::CritFail) {
        к.авторитет -= 1;
        к.текст = Some("Соседи видели слабость. Они придут с «предложением помощи». Авторитет -1.");
    }

    // ────────────────────────────────────────────────────────────
    // ПРОКЛЯТЫЕ_ЛИСТЬЯ: каждые 3 хода настроение -1
    if tribe.has_flag(flags::ПРОКЛЯТЫЕ_ЛИСТЬЯ) && tribe.turn % 3 == 0 {
        к.настроение -= 1;
        к.текст = Some("Проклятые листья у входа. Все их видят. Настроение ухудшается.");
    }

    // ЗНАНИЯ > 50: шаман объясняет листьям что с ними не так, флаг снимается
    if tribe.has_flag(flags::ПРОКЛЯТЫЕ_ЛИСТЬЯ) && tribe.knowledge >= 50 {
        к.флаг_снять = Some(flags::ПРОКЛЯТЫЕ_ЛИСТЬЯ);
        к.текст = Some("Шаман наконец понял что это просто листья. Выбросил. Всем полегчало.");
    }

    // ────────────────────────────────────────────────────────────
    // СМЕНА_ВОЖДЯ: авторитет падает до нуля при установке флага
    if tribe.has_flag(flags::СМЕНА_ВОЖДЯ) {
        к.авторитет = -tribe.authority; // сброс к нулю
        к.флаг_снять = Some(flags::СМЕНА_ВОЖДЯ); // флаг разовый
        к.текст = Some("Новый вождь. Старый авторитет — ноль. Всё нужно строить заново.");
    }

    // ────────────────────────────────────────────────────────────
    // МЕДВЕДЬ_ПОМНИТ: каждые 5 ходов проверка
    if tribe.has_flag(flags::МЕДВЕДЬ_ПОМНИТ) && tribe.turn % 5 == 0 {
        // Уже учтено в effective_target, но добавляем нарратив
        к.текст = Some("Медведь где-то помнит. Охотники нервничают.");
    }

    // ────────────────────────────────────────────────────────────
    // ОБЩЕЕ_ВИДЕНИЕ: племя видело одно и то же — временный бонус к знаниям
    if tribe.has_flag(flags::ОБЩЕЕ_ВИДЕНИЕ) && действие == 2 {
        к.знания += 5;
        к.флаг_снять = Some(flags::ОБЩЕЕ_ВИДЕНИЕ); // разовый
        к.текст = Some("Видение ещё свежо. Думается иначе. +5 знаний к размышлениям.");
    }

    // ────────────────────────────────────────────────────────────
    // ДОЛГ_КРОВИ: каждые 4 хода напоминание об угрозе набега
    if tribe.has_flag(flags::ДОЛГ_КРОВИ) && tribe.turn % 4 == 0 {
        к.настроение -= 1;
        к.текст = Some("Долг крови висит над племенем. Когда они придут?");
    }

    // СОЮЗ_ТУПЫХ: защита от «тупых» набегов
    if tribe.has_flag(flags::СОЮЗ_ТУПЫХ) && исход == Outcome::CritFail
        && действие == 3 {
        к.текст = Some("Наши тупые союзники случайно отвлекли врагов. Повезло.");
    }

    к
}

// ═══════════════════════════════════════════════════════════════════
// ЧАСТЬ 4: ФАЗА DM — мир живёт без команды
// Проверяется каждый ход ПОСЛЕ действий игрока.
// ═══════════════════════════════════════════════════════════════════

pub struct ФазаDM {
    pub события: [Option<&'static str>; 8],
    pub эффекты: [Eff; 8],
    pub количество: usize,
}

impl ФазаDM {
    const fn пусто() -> Self {
        Self {
            события: [None; 8],
            эффекты: [Eff::Ничего; 8],
            количество: 0,
        }
    }

    fn добавить(&mut self, текст: &'static str, эфф: Eff) {
        if self.количество < 8 {
            self.события[self.количество] = Some(текст);
            self.эффекты[self.количество] = эфф;
            self.количество += 1;
        }
    }
}

/// Фаза DM — все проверки "пассивного мира".
/// Вызывается один раз за ход после всех действий игрока.
pub fn фаза_dm(tribe: &Tribe) -> ФазаDM {
    let mut dm = ФазаDM::пусто();

    // ── ГОЛОД ──────────────────────────────────────────────────

    if tribe.food == 0 {
        dm.добавить(
            "Еды нет. Племя голодает. Это критично.",
            Eff::Настроение(-2),
        );
    }

    if tribe.food < 0 {
        dm.добавить(
            "ГОЛОД. Кто-то не пережил ночь.",
            Eff::Народ(-1),
        );
    }

    // ── УНЫНИЕ ─────────────────────────────────────────────────

    if tribe.mood <= -8 {
        dm.добавить(
            "Племя на грани. Люди не хотят работать. -1 ОД этот ход.",
            Eff::ОД(1),
        );
    }

    // ── АВТОРИТЕТ НИЖЕ ДНА ─────────────────────────────────────

    if tribe.authority <= -8 && tribe.turn % 3 == 0 {
        dm.добавить(
            "Вождя открыто игнорируют. Кто-то говорит про выборы. флаг СМЕНА_ВОЖДЯ?",
            Eff::Флаг(flags::СМЕНА_ВОЖДЯ),
        );
    }

    // ── ПЕРЕНАСЕЛЕНИЕ ──────────────────────────────────────────

    if tribe.population > 25 && tribe.food < 15 {
        dm.добавить(
            "Племя выросло. Еды не хватает на всех. Голод приближается.",
            Eff::Настроение(-1),
        );
    }

    // ── ФЛАГИ: МЕДВЕДЬ ПОМНИТ ──────────────────────────────────

    if tribe.has_flag(flags::МЕДВЕДЬ_ПОМНИТ) && tribe.turn % 5 == 0 {
        dm.добавить(
            "Медведь снова видел ваших охотников. Он не забыл.",
            Eff::Настроение(-1),
        );
    }

    // ── ФЛАГИ: ВРАГИ ЗНАЮТ ─────────────────────────────────────

    if tribe.has_flag(flags::ВРАГИ_ЗНАЮТ) && tribe.turn % 6 == 0 {
        dm.добавить(
            "Враги знают где вы. Разведчики замечены у границы.",
            Eff::Набег(3),
        );
    }

    // ── ФЛАГИ: ОКРУЖЕНЫ ────────────────────────────────────────

    if tribe.has_flag(flags::ОКРУЖЕНЫ) {
        dm.добавить(
            "ОКРУЖЕНЫ. Враги со всех сторон. Разведка невозможна.",
            Eff::ОД(1),
        );
    }

    // ── ТИХИЙ ХОД: небольшие естественные эффекты ──────────────

    // Еда постепенно убывает (племя ест каждый ход)
    // Это базовый расход — 1 еда на 5 человек в ход
    // (уже учтено в tribe.rs через turn_end())

    dm
}

